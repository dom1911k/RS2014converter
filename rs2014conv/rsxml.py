"""Rocksmith 2014 arrangement XML writer (single difficulty level = the full chart)."""

from __future__ import annotations

import datetime as _dt
from xml.sax.saxutils import escape

from .model import Chart, Note


def _t(x: float) -> str:
    return f"{max(0.0, x):.3f}"


def _attr(s: str) -> str:
    return escape(s, {'"': "&quot;"})


def _note_xml(n: Note) -> str:
    a = [f'time="{_t(n.time)}"', f'string="{n.string}"', f'fret="{n.fret}"']
    if n.sustain > 0:
        a.append(f'sustain="{_t(n.sustain)}"')
    if n.link_next:
        a.append('linkNext="1"')
    if n.accent:
        a.append('accent="1"')
    if n.hammer_on:
        a.append('hammerOn="1"')
    if n.pull_off:
        a.append('pullOff="1"')
    if n.harmonic:
        a.append('harmonic="1"')
    if n.mute:
        a.append('mute="1"')
    if n.palm_mute:
        a.append('palmMute="1"')
    if n.tremolo:
        a.append('tremolo="1"')
    if n.vibrato:
        a.append('vibrato="80"')
    if n.slide_to >= 0:
        a.append(f'slideTo="{n.slide_to}"')
    if n.slide_unpitch_to >= 0:
        a.append(f'slideUnpitchTo="{n.slide_unpitch_to}"')
    if n.slap:
        a.append('slap="1"')
    if n.pop:
        a.append('pluck="1"')
    if n.tap:
        a.append('tap="1"')
    if n.bend > 0 and n.sustain > 0:
        a.append(f'bend="{n.bend:g}"')
        peak = n.time + n.sustain / 2
        return (f'        <note {" ".join(a)}>\n          <bendValues count="1">\n'
                f'            <bendValue time="{_t(peak)}" step="{n.bend:g}" />\n'
                f'          </bendValues>\n        </note>')
    return f'        <note {" ".join(a)} />'


def write(path, chart: Chart, meta: dict, offsets: list[int], anchors: list[tuple[float, int, int]],
          bass_pick: bool, tone_key: str) -> None:
    beats = chart.beats
    notes = chart.notes
    sections = chart.sections
    start_beat = beats[0].time
    ibis = [b.time - a.time for a, b in zip(beats, beats[1:]) if b.time > a.time]
    avg_tempo = 60.0 / sorted(ibis)[len(ibis) // 2] if ibis else 120.0
    standard = all(o == 0 for o in offsets[:4])

    def has(attr):
        return int(any(getattr(n, attr) for n in notes))

    props = {
        "represent": 1, "bonusArr": 0, "standardTuning": int(standard), "nonStandardChords": 0,
        "barreChords": 0, "powerChords": 0, "dropDPower": 0, "openChords": 0, "fingerPicking": 0,
        "pickDirection": 0, "doubleStops": 0, "palmMutes": has("palm_mute"), "harmonics": has("harmonic"),
        "pinchHarmonics": 0, "hopo": int(any(n.hammer_on or n.pull_off for n in notes)), "tremolo": has("tremolo"),
        "slides": int(any(n.slide_to >= 0 for n in notes)),
        "unpitchedSlides": int(any(n.slide_unpitch_to >= 0 for n in notes)),
        "bends": int(any(n.bend > 0 for n in notes)), "tapping": has("tap"), "vibrato": has("vibrato"),
        "fretHandMutes": has("mute"), "slapPop": int(any(n.slap or n.pop for n in notes)),
        "twoFingerPicking": int(not bass_pick), "fifthsAndOctaves": 0, "syncopation": 0,
        "bassPick": int(bass_pick), "sustain": int(any(n.sustain > 0 for n in notes)),
        "pathLead": 0, "pathRhythm": 0, "pathBass": 1,
    }

    # Phrases: COUNT (empty, first beat) + one per section name + END at the final noguitar section.
    phrase_names: list[str] = ["COUNT"]
    iterations: list[tuple[float, int]] = [(start_beat, 0)]
    for s in sections:
        name = "END" if s.name == "noguitar" and s is sections[-1] else s.name
        if name not in phrase_names:
            phrase_names.append(name)
        iterations.append((s.time, phrase_names.index(name)))
    if "END" not in phrase_names:
        phrase_names.append("END")
        iterations.append((beats[-1].time, phrase_names.index("END")))

    sec_numbers: dict[str, int] = {}
    sec_xml = []
    for s in sections:
        sec_numbers[s.name] = sec_numbers.get(s.name, 0) + 1
        sec_xml.append(f'    <section name="{s.name}" number="{sec_numbers[s.name]}" startTime="{_t(s.time)}" />')

    events = [f'    <event time="{_t(ts.time)}" code="TS:{ts.numerator}/{ts.denominator}" />'
              for ts in chart.time_signatures]

    out = ['<?xml version="1.0" encoding="utf-8"?>', '<song version="8">',
           "<!-- Generated by make_cdlc (RS2014converter): single difficulty level, no dynamic difficulty -->",
           f"  <title>{escape(meta['title'])}</title>", "  <arrangement>Bass</arrangement>", "  <part>1</part>",
           f"  <offset>{-start_beat:.3f}</offset>", "  <centOffset>0</centOffset>",
           f"  <songLength>{_t(chart.song_length)}</songLength>",
           f"  <songNameSort>{escape(meta['title_sort'])}</songNameSort>",
           f"  <startBeat>{_t(start_beat)}</startBeat>", f"  <averageTempo>{avg_tempo:.3f}</averageTempo>",
           "  <tuning " + " ".join(f'string{i}="{o}"' for i, o in enumerate(offsets[:6])) + " />",
           "  <capo>0</capo>", f"  <artistName>{escape(meta['artist'])}</artistName>",
           f"  <artistNameSort>{escape(meta['artist_sort'])}</artistNameSort>",
           f"  <albumName>{escape(meta['album'])}</albumName>",
           f"  <albumNameSort>{escape(meta['album_sort'])}</albumNameSort>",
           f"  <albumYear>{meta['year']}</albumYear>", "  <crowdSpeed>1</crowdSpeed>",
           "  <arrangementProperties " + " ".join(f'{k}="{v}"' for k, v in props.items()) + " />",
           f"  <lastConversionDateTime>{_dt.datetime.now().strftime('%m-%d-%y %H:%M')}</lastConversionDateTime>",
           f'  <phrases count="{len(phrase_names)}">']
    out += [f'    <phrase maxDifficulty="0" name="{_attr(p)}" />' for p in phrase_names]
    out += ["  </phrases>", f'  <phraseIterations count="{len(iterations)}">']
    out += [f'    <phraseIteration time="{_t(t)}" phraseId="{pid}" />' for t, pid in iterations]
    out += ["  </phraseIterations>", '  <newLinkedDiffs count="0" />', '  <linkedDiffs count="0" />',
            '  <phraseProperties count="0" />', '  <chordTemplates count="0" />',
            '  <fretHandMuteTemplates count="0" />', f'  <ebeats count="{len(beats)}">']
    for b in beats:
        m = f' measure="{b.measure}"' if b.measure >= 0 else ""
        out.append(f'    <ebeat time="{_t(b.time)}"{m} />')
    out += ["  </ebeats>", f"  <tonebase>{escape(tone_key)}</tonebase>",
            f'  <sections count="{len(sec_xml)}">', *sec_xml, "  </sections>",
            f'  <events count="{len(events)}">', *events, "  </events>",
            '  <transcriptionTrack difficulty="-1">', '    <notes count="0" />', '    <chords count="0" />',
            '    <anchors count="0" />', '    <handShapes count="0" />', "  </transcriptionTrack>",
            '  <levels count="1">', '    <level difficulty="0">', f'      <notes count="{len(notes)}">']
    out += [_note_xml(n) for n in notes]
    out += ["      </notes>", '      <chords count="0" />', '      <fretHandMutes count="0" />',
            f'      <anchors count="{len(anchors)}">']
    out += [f'        <anchor time="{_t(t)}" fret="{f}" width="{w:.3f}" />' for t, f, w in anchors]
    out += ["      </anchors>", '      <handShapes count="0" />', "    </level>", "  </levels>", "</song>", ""]
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
